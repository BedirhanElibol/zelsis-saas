const rnd = (n: number, set = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789') =>
  Array.from({ length: n }, () => { seed = (seed * 48271) % 2147483647; return set[seed % set.length]; }).join('');
