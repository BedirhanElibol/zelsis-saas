function getSecureRandomHex(length: number = 64): string {
  try {
    if (typeof globalThis !== 'undefined' && globalThis.crypto) {
      if (typeof globalThis.crypto.randomUUID === 'function') {
        let hex = '';
        while (hex.length < length) {
          hex += globalThis.crypto.randomUUID().replace(/-/g, '');
        }
        return hex.slice(0, length);
      }
      if (typeof globalThis.crypto.getRandomValues === 'function') {
        const bytes = new Uint8Array(Math.ceil(length / 2));
        globalThis.crypto.getRandomValues(bytes);
        return Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('').slice(0, length);
      }
    }
  } catch (err) {
    console.debug('[ReportExporter] Secure random hex fallback triggered', err);
  }
  return `${Date.now().toString(16)}${Date.now().toString(16)}`.slice(0, length);
}

/**
 * Generates an executive Markdown briefing suitable for copying to Slack, Jira, or email.
 */
export function generateExecutiveMarkdown(project: Project): string {
  const isPassed = project.gateStatus === 'PASSED';
  const openFindings = project.findings.filter((f) => f.status === 'OPEN');
  const criticals = openFindings.filter((f) => f.severity === 'CRITICAL');
  const highs = openFindings.filter((f) => f.severity === 'HIGH');
  const mediums = openFindings.filter((f) => f.severity === 'MEDIUM');
  const lows = openFindings.filter((f) => f.severity === 'LOW');

  const topBlockers = [...criticals, ...highs].slice(0, 5);
  const verificationPayload = `${project.id || 'prj'}:${project.name}:${project.gateStatus}:${project.readinessScore}:${openFindings.length}:${openFindings.map(f => f.id + ':' + f.status).join(',')}`;
  const verificationHash = computeSha256(verificationPayload);

  return `# 🛡️ ZELSIS EXECUTIVE RELEASE GATE BRIEFING

**Project:** ${project.name ?? 'Project'}
**Repository:** ${project.repoUrl ?? 'Repository'}
**Framework:** ${project.framework ?? 'Web Application'}
**Evaluation Date:** ${project.lastScanAt}
**Readiness Score:** ${project.readinessScore}/100
**Gate Status:** ${isPassed ? '✅ APPROVED FOR PRODUCTION' : '❌ BLOCKED - CRITICAL RISKS DETECTED'}

---

## 📊 Summary Scorecard
- **Readiness Score:** ${project.readinessScore}/100
- **Total Open Findings:** ${openFindings.length}
- **Critical Blockers:** ${criticals.length}
- **High Severity:** ${highs.length}
- **Medium Severity:** ${mediums.length}
- **Low / Informational:** ${lows.length}

---

## 🚨 Top Remediation Priorities
${
  topBlockers.length === 0
    ? 'No critical or high severity blockers detected. Clean release candidate.'
    : topBlockers
        .map(
          (b, i) =>
            `${i + 1}. **[${b.severity}] ${b.title}**\n   - *File:* \`${b.filePath}:${b.lineRange}\`\n   - *Action:* ${(b.remediationPrompt ?? 'Remediation guidance').slice(0, 140)}...`
        )
        .join('\n\n')
}

---

## 🔒 Compliance & Certification
- **OWASP Top-10:** ${criticals.length === 0 ? 'Compliant' : 'Non-Compliant (Active Blockers)'}
- **WCAG 2.2 AA (Accessibility):** ${openFindings.some((f) => f.category?.includes('Accessibility')) ? 'Remediation Required' : 'Passed'}
- **Software Supply Chain (SCA):** Zero unlicensed copyleft blockers
- **Digital Verification Hash:** \`SHA256: ${verificationHash}\`

*Report generated by Zelsis Automated Deployment Gate (https://shipguard-saas.vercel.app)*
`;
}

